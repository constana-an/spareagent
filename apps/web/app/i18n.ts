const dictionaries: Record<Lang, Record<Key, string>> = { en, zh };

export type Translate = (key: Key, vars?: Vars) => string;

export function translator(lang: Lang): Translate {
  return (key, vars) => {
    let text = dictionaries[lang][key] ?? en[key] ?? key;
    for (const [name, value] of Object.entries(vars || {}))
      text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("sa_lang");
    if (saved === "en" || saved === "zh") return saved;
  } catch {}
  return "zh";
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem("sa_lang", lang);
  } catch {}
}
